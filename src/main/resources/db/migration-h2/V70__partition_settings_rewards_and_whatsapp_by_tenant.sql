-- 1. app_settings: clave única por salón con id sustituto como PK.
--    En H2 añadir una columna IDENTITY con ALTER no la deja autogenerada para nuevos
--    inserts, así que la tabla se recrea copiando los datos al salón principal.
CREATE TABLE app_settings_v70 (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL DEFAULT 1,
    setting_key VARCHAR(100) NOT NULL,
    setting_value TEXT,
    description VARCHAR(200),
    CONSTRAINT uk_app_settings_tenant_key UNIQUE (tenant_id, setting_key)
);
INSERT INTO app_settings_v70 (tenant_id, setting_key, setting_value, description)
    SELECT 1, setting_key, setting_value, description FROM app_settings;
DROP TABLE app_settings;
ALTER TABLE app_settings_v70 RENAME TO app_settings;

-- 2. Catálogo de recompensas de fidelización
-- (H2) V43 convirtió los id a BIGINT plano y perdió la autogeneración; en Postgres se conserva.
ALTER TABLE loyalty_rewards ALTER COLUMN id SET GENERATED BY DEFAULT;
ALTER TABLE loyalty_rewards ALTER COLUMN id RESTART WITH 1000;
ALTER TABLE loyalty_reward_history ALTER COLUMN id SET GENERATED BY DEFAULT;
ALTER TABLE loyalty_reward_history ALTER COLUMN id RESTART WITH 1000;
ALTER TABLE loyalty_rewards ADD COLUMN IF NOT EXISTS tenant_id BIGINT NOT NULL DEFAULT 1;
CREATE INDEX IF NOT EXISTS idx_loyalty_rewards_tenant_order ON loyalty_rewards(tenant_id, order_index);

-- 3. Bandeja de entrada de WhatsApp
ALTER TABLE incoming_whatsapp_messages ADD COLUMN IF NOT EXISTS tenant_id BIGINT NOT NULL DEFAULT 1;
CREATE INDEX IF NOT EXISTS idx_incoming_wa_msgs_tenant_created ON incoming_whatsapp_messages(tenant_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_incoming_wa_msgs_tenant_read ON incoming_whatsapp_messages(tenant_id, is_read);

-- 4. Cola de mensajes WhatsApp fallidos
ALTER TABLE whatsapp_outbox_messages ADD COLUMN IF NOT EXISTS tenant_id BIGINT NOT NULL DEFAULT 1;
CREATE INDEX IF NOT EXISTS idx_wa_outbox_tenant_status ON whatsapp_outbox_messages(tenant_id, status);
