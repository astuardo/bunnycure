-- ==========================================================
-- V68: Create Invoice Outbox table for Resilient Billing (H2)
-- ==========================================================

CREATE TABLE IF NOT EXISTS invoice_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL DEFAULT 1,
    appointment_id BIGINT NOT NULL,
    customer_id BIGINT NOT NULL,
    customer_rut VARCHAR(20) NOT NULL,
    customer_name VARCHAR(120),
    customer_email VARCHAR(120),
    amount NUMERIC(12, 2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    attempts INT NOT NULL DEFAULT 0,
    max_attempts INT NOT NULL DEFAULT 5,
    last_error VARCHAR(1000),
    folio VARCHAR(50),
    next_attempt_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_invoice_outbox_status_attempt ON invoice_outbox(status, next_attempt_at);
CREATE INDEX IF NOT EXISTS idx_invoice_outbox_tenant_status ON invoice_outbox(tenant_id, status);
CREATE INDEX IF NOT EXISTS idx_invoice_outbox_appointment ON invoice_outbox(appointment_id);
